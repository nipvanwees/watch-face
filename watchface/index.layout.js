// Two metric groups: heart rate over water at 9 o'clock, steps beside stretch at 6.
// Each metric is a 40x44 icon centered on (x, y) with its value to the right, bottom-aligned with the icon.
// Water and stretch get a generous invisible tap area; heart rate and steps are display-only.
const ICON_W = px(40);
const ICON_H = px(44);
const VALUE_W = px(70);
const VALUE_H = px(30);

function metric(x, y, valueX, valueBottom, tap) {
  return {
    icon: { x: Math.round(x - ICON_W / 2), y: Math.round(y - ICON_H / 2) },
    value: {
      x: valueX,
      y: valueBottom - VALUE_H,
      w: VALUE_W,
      h: VALUE_H,
      font: FONT,
      color: COLORS.text,
      text_size: px(24),
      align_h: hmUI.align.LEFT,
      align_v: hmUI.align.BOTTOM,
    },
    tap: tap && { ...tap, color: 0x000000, alpha: 0 },
  };
}

